"""Funciones matemáticas de la calculadora."""


def suma(a, b):
    return a + b


def resta(a, b):
    return a - b


def multiplicacion(a, b):
    return a * b


def division(a, b):
    return a / b


def potencia(base, exponente):
    return base ** exponente


def modulo(a, b):
    return a % b
